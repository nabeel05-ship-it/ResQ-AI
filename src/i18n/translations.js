export const getTranslation = (langNameOrCode = 'English') => {
  // Support both code ('hi') and name ('Hindi')
  let lang = langNameOrCode;
  if (!lang) lang = 'English';
  
  const foundByCode = SUPPORTED_LANGUAGES.find(
    (l) => l.code.toLowerCase() === String(lang).toLowerCase()
  );
  if (foundByCode) {
    lang = foundByCode.name;
  }

  const selected = TRANSLATIONS[lang] || TRANSLATIONS['English'];
  const english = TRANSLATIONS['English'];

  // Return deep proxy/merged fallback so any missing key automatically falls back to English
  const res = deepMergeFallback(selected, english);

  // Normalize nearby tabs so both singular/plural (hospital/hospitals, fire/fire_station) always resolve accurately
  if (res.nearby && res.nearby.tabs) {
    const tabs = res.nearby.tabs;
    const hospitalTranslation = tabs.hospitals || tabs.hospital;
    const fireTranslation = tabs.fire || tabs.fire_station;
    if (hospitalTranslation) {
      tabs.hospitals = hospitalTranslation;
      tabs.hospital = hospitalTranslation;
    }
    if (fireTranslation) {
      tabs.fire = fireTranslation;
      tabs.fire_station = fireTranslation;
    }
  }

  // Backward-compatibility legacy shortcuts:
  res.medical = res.home?.categories?.medical || "Medical";
  res.fire = res.home?.categories?.fire || "Fire";
  res.accident = res.home?.categories?.accident || "Accident";
  res.crime = res.home?.categories?.crime || "Crime";
  res.disaster = res.home?.categories?.disaster || "Disaster";
  res.homeCat = res.home?.categories?.home || "Home";
  res.hello = res.home?.welcomeBack || "Hello";
  res.emergency = res.home?.systemReady || "Emergency Response";
  res.aiGuide = res.home?.heroSub || "AI Emergency Guide";
  res.selectEmergency = res.home?.categories?.medical || "Select Emergency";
  res.describeEmergency = res.home?.describeEmergency || "Describe emergency...";
  res.getHelp = res.home?.getHelp || "Get Help";
  res.listening = res.home?.listening || "Listening...";
  res.quickCall = res.home?.quickNumbers || "Emergency Numbers";
  res.logout = res.nav?.logout || "Logout";
  res.voiceError = res.guidance?.voiceError || "Voice error. Please type.";
  res.voiceFailed = res.guidance?.voiceError || "Voice error. Please type.";
  res.typeError = res.guidance?.inputPlaceholder || "Please describe your emergency.";
  res.guideBtn = res.nav?.askAi || "AI Guide";

  return res;
};

function deepMergeFallback(target, fallback) {
  if (!target && !fallback) return {};
  if (!target) return fallback;
  if (!fallback) return target;

  const result = { ...fallback, ...target };
  for (const key of Object.keys(fallback)) {
    if (
      typeof fallback[key] === 'object' &&
      fallback[key] !== null &&
      !Array.isArray(fallback[key])
    ) {
      result[key] = deepMergeFallback(target[key] || {}, fallback[key]);
    } else if (target[key] === undefined) {
      result[key] = fallback[key];
    }
  }
  return result;
}

