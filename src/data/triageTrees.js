export const getTriageTree = (id) => TRIAGE_TREES[id] || null;

export const getTriageContent = (tree, lang) => {
  if (!tree) return null;
  const fallback = "English";
  const selectedLang = lang || fallback;
  return {
    title: (tree.title && (tree.title[selectedLang] || tree.title[fallback])) || "",
    callLabel: (tree.callLabel && (tree.callLabel[selectedLang] || tree.callLabel[fallback])) || "",
    redFlags: (tree.redFlags && (tree.redFlags[selectedLang] || tree.redFlags[fallback])) || [],
    steps: (tree.steps && (tree.steps[selectedLang] || tree.steps[fallback])) || [],
  };
};
